package com.bhavesh.sqlmastery.config;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.HashMap;
import java.util.List;
import java.util.Map;

import org.springframework.boot.SpringApplication;
import org.springframework.boot.env.EnvironmentPostProcessor;
import org.springframework.core.env.ConfigurableEnvironment;
import org.springframework.core.env.MapPropertySource;

/**
 * Loads {@code .env} from the project root into the Spring environment.
 *
 * <p>Without this, {@code ./mvnw spring-boot:run} would only work for someone
 * who had remembered to {@code set -a; . ../.env} first — which makes "a fresh
 * checkout starts after running two documented commands" untrue in a way that
 * is annoying to discover. The file is generated by
 * {@code scripts/provision-db.sh}, is listed in {@code .gitignore} and is the
 * only place the generated database passwords are written.
 *
 * <p>Real environment variables and {@code -D} properties take priority: this
 * source is added with {@code addLast}, so a container or CI job that sets
 * {@code SQLMASTERY_DB_HOST} wins over a stale {@code .env} on a laptop.
 *
 * <p>Values are never logged. A parse failure is reported by key name only.
 */
public class DotenvEnvironmentPostProcessor implements EnvironmentPostProcessor {

    private static final String SOURCE_NAME = "sqlmastery-dotenv";

    /** The backend runs from backend/, so the project root is one level up. */
    private static final List<String> CANDIDATES = List.of(".env", "../.env", "../../.env");

    @Override
    public void postProcessEnvironment(ConfigurableEnvironment environment, SpringApplication application) {
        for (String candidate : CANDIDATES) {
            Path path = Path.of(candidate).toAbsolutePath().normalize();
            if (Files.isRegularFile(path)) {
                Map<String, Object> values = parse(path);
                if (!values.isEmpty()) {
                    environment.getPropertySources().addLast(new MapPropertySource(SOURCE_NAME, values));
                }
                return;
            }
        }
    }

    private Map<String, Object> parse(Path path) {
        Map<String, Object> values = new HashMap<>();
        List<String> lines;
        try {
            lines = Files.readAllLines(path, StandardCharsets.UTF_8);
        } catch (IOException e) {
            // Not fatal: the application can still start from real environment
            // variables. Report the path, never the contents.
            System.err.println("Could not read " + path + ": " + e.getMessage());
            return values;
        }
        for (String raw : lines) {
            String line = raw.trim();
            if (line.isEmpty() || line.startsWith("#")) {
                continue;
            }
            int eq = line.indexOf('=');
            if (eq <= 0) {
                continue;
            }
            String key = line.substring(0, eq).trim();
            String value = unquote(line.substring(eq + 1).trim());
            values.put(key, value);
        }
        return values;
    }

    private String unquote(String value) {
        if (value.length() >= 2
                && ((value.startsWith("\"") && value.endsWith("\""))
                    || (value.startsWith("'") && value.endsWith("'")))) {
            return value.substring(1, value.length() - 1);
        }
        return value;
    }
}
