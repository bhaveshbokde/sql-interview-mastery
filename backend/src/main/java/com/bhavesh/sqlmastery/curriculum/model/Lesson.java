package com.bhavesh.sqlmastery.curriculum.model;

import java.util.List;

import com.bhavesh.sqlmastery.playground.dto.QueryResult;
import com.fasterxml.jackson.annotation.JsonIgnoreProperties;

/**
 * One lesson, as authored in {@code resources/curriculum/lessons/**.yaml}.
 *
 * <p>The record's components are the fourteen things every lesson in this
 * curriculum is required to have, so "is this lesson complete?" is a question
 * the type system participates in rather than a checklist somebody keeps in
 * their head. {@code CurriculumLoader} refuses to load a lesson that leaves any
 * of the required ones empty, which means an incomplete lesson fails the
 * startup rather than quietly shipping as a page with a blank section.
 *
 * <p>The one thing an author does <em>not</em> write is the expected output of
 * an example. Those are generated by executing the SQL against the real
 * dataset ({@code tools/verify_sql.py}) and are merged in at load time. Hand-
 * written expected output is how a tutorial comes to contain a result that the
 * query does not actually produce.
 *
 * @param prerequisites       lesson ids that should be read first (element 1)
 * @param objectives          what the reader will be able to do (element 1)
 * @param concept             the explanation, in Markdown (element 2)
 * @param syntax              forms and rules (element 3)
 * @param sampleTables        the dataset tables this lesson uses (element 4)
 * @param examples            runnable SQL with recorded output and a
 *                            walkthrough (elements 5, 6 and 7)
 * @param edgeCases           NULL, duplicate and boundary behaviour, each with
 *                            a query that demonstrates it (element 8)
 * @param pitfalls            common errors and misconceptions (element 9)
 * @param performance         performance notes, or null where there is nothing
 *                            honest to say (element 10)
 * @param interviewQuestions  questions with model answers (element 11)
 * @param exercises           practice, with difficulty labels (element 12)
 * @param checklist           the revision checklist (element 13)
 * @param related             related lessons and suggested next topics
 *                            (element 14)
 * @param dialect             what is standard SQL, what is PostgreSQL-specific
 *                            and how MySQL differs
 */
@JsonIgnoreProperties(ignoreUnknown = false)
public record Lesson(
        String id,
        String moduleId,
        int position,
        String title,
        String slug,
        String difficulty,
        int estimatedMinutes,
        String summary,
        List<String> tags,
        List<String> prerequisites,
        List<String> objectives,
        String concept,
        List<SyntaxForm> syntax,
        List<String> sampleTables,
        List<Example> examples,
        List<EdgeCase> edgeCases,
        List<Pitfall> pitfalls,
        String performance,
        List<QuestionAnswer> interviewQuestions,
        List<Exercise> exercises,
        List<String> checklist,
        List<String> related,
        Dialect dialect) {

    /** A syntax form with the rules that govern it. */
    public record SyntaxForm(String form, String notes) {
    }

    /**
     * A runnable example.
     *
     * @param schema which dataset to run against. Null means {@code learning}.
     *               Present because several lessons make their point by
     *               running the same query against {@code learning_alt},
     *               where the ties and empty tables live — and because
     *               {@code CurriculumSql} only reads a {@code schema} that is
     *               a sibling of the {@code sql}, so it has to be a component
     *               of this record rather than of its parent.
     * @param result the recorded output, merged in from the generated file at
     *               load time. Null in the authored YAML, and null here only if
     *               the SQL has never been successfully executed — which the
     *               loader treats as a failure.
     */
    public record Example(String title, String sql, String schema, String walkthrough, QueryResult result) {
    }

    /**
     * A boundary case worth seeing rather than being told about.
     *
     * @param schema which dataset to run against; see {@link Example#schema()}
     */
    public record EdgeCase(String title, String body, String sql, String schema, QueryResult result) {
    }

    /** A mistake, why it is made, and what to do instead. */
    public record Pitfall(String mistake, String why, String fix) {
    }

    /** An interview question with a model answer. */
    public record QuestionAnswer(String question, String answer) {
    }

    /**
     * A practice exercise.
     *
     * @param solutionSql the reference answer, executed and recorded like any
     *                    other example so the exercise cannot ask for something
     *                    its own answer does not produce
     */
    public record Exercise(
            String prompt,
            String difficulty,
            String hint,
            String solutionSql,
            QueryResult result) {
    }

    /**
     * Portability notes.
     *
     * @param standard what the SQL standard says
     * @param postgres what PostgreSQL adds or does differently
     * @param mysql    how MySQL differs, where an interviewer is likely to ask
     */
    public record Dialect(String standard, String postgres, String mysql) {
    }
}
